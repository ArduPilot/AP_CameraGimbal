#!/usr/bin/env python3
"""Writes a PEM bundle of CA certificates as a C++ header holding one string constant, for the cameras
that build the roots cloud upload trusts into camera-app (no file has to be installed beside it).
Usage: embed_ca.py bundle.pem output.h"""
import os
import sys
from pathlib import Path


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    text = Path(sys.argv[1]).read_text(encoding='ascii')
    if '-----BEGIN CERTIFICATE-----' not in text:
        raise SystemExit(sys.argv[1] + ': no certificates')
    lines = ['// Generated by tools/embed_ca.py from ' + Path(sys.argv[1]).name + '; do not edit.',
             'static const char upload_embedded_ca[] =']
    for line in text.splitlines():
        lines.append('    "' + line.replace('\\', '\\\\').replace('"', '\\"') + '\\n"')
    lines[-1] += ';'
    out = Path(sys.argv[2])
    out.parent.mkdir(parents=True, exist_ok=True)
    # Builds that run in parallel may all make the header: each writes its own file, then renames it into place.
    temporary = out.with_suffix(out.suffix + '.' + str(os.getpid()) + '.tmp')
    try:
        temporary.write_text('\n'.join(lines) + '\n', encoding='ascii')
        temporary.replace(out)
    finally:
        temporary.unlink(missing_ok=True)


main()
